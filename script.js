/* ---------- Gallery: auto-scroll + drag ---------- */
(function gallery() {
  const track = document.getElementById("gallery-track");
  const inner = document.getElementById("gallery-inner");
  if (!track || !inner) return;

  let offset = 0;
  let speed = 0.4;          // px per frame for auto-scroll
  let paused = false;
  let isDown = false;
  let startX = 0;
  let startOffset = 0;
  let half = 0;

  function measure() { half = inner.scrollWidth / 2; }
  measure();
  window.addEventListener("resize", measure);
  window.addEventListener("load", measure);

  function wrap() {
    if (half <= 0) return;
    if (offset <= -half) offset += half;
    if (offset > 0) offset -= half;
  }

  function tick() {
    if (!paused && !isDown) {
      offset -= speed;
      wrap();
      inner.style.transform = `translateX(${offset}px)`;
    }
    requestAnimationFrame(tick);
  }
  requestAnimationFrame(tick);

  track.addEventListener("mouseenter", () => (paused = true));
  track.addEventListener("mouseleave", () => (paused = false));

  function pointerDown(x) {
    isDown = true;
    startX = x;
    startOffset = offset;
    track.classList.add("is-dragging");
  }
  function pointerMove(x) {
    if (!isDown) return;
    offset = startOffset + (x - startX);
    wrap();
    inner.style.transform = `translateX(${offset}px)`;
  }
  function pointerUp() {
    isDown = false;
    track.classList.remove("is-dragging");
  }

  track.addEventListener("mousedown", (e) => { e.preventDefault(); pointerDown(e.pageX); });
  window.addEventListener("mousemove", (e) => pointerMove(e.pageX));
  window.addEventListener("mouseup", pointerUp);

  track.addEventListener("touchstart", (e) => pointerDown(e.touches[0].pageX), { passive: true });
  track.addEventListener("touchmove", (e) => pointerMove(e.touches[0].pageX), { passive: true });
  track.addEventListener("touchend", pointerUp);
})();

